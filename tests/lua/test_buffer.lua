local mumble = require("mumble")
-- Find the harness next to this file, wherever the test is run from
package.path = (arg[0]:match("^(.*[/\\])") or "./") .. "?.lua;" .. package.path
local t = require("harness")

t.test("constructors", function()
	local b = mumble.buffer()
	t.eq(b.capacity, 1024)
	t.eq(b.length, 0)
	t.eq(#b, 0)
	t.eq(b:isEmpty(), true)

	t.eq(mumble.buffer(16).capacity, 16)

	local data = mumble.buffer("abc")
	t.eq(data.length, 3)
	t.eq(data:read("*a"), "abc")

	t.errors("number or string expected", mumble.buffer, {})
	t.truthy(tostring(b):find("^mumble.buffer: "))
end)

t.test("typed values roundtrip", function()
	local b = mumble.buffer(4)
	t.eq(b:writeByte(200), 1)
	t.eq(b:writeShort(-1234), 2)
	t.eq(b:writeInt(-123456789), 4)
	t.eq(b:writeFloat(1.5), 4)
	t.eq(b:writeDouble(math.pi), 8)
	t.eq(b:writeBool(true), 1)
	t.eq(b:writeBoolean(false), 1)
	t.truthy(b.capacity >= b.write_head)

	t.eq(b:readByte(), 200)
	t.eq(b:readShort(), -1234)
	t.eq(b:readInt(), -123456789)
	t.eq(b:readFloat(), 1.5)
	t.eq(b:readDouble(), math.pi)
	t.eq(b:readBool(), true)
	t.eq(b:readBoolean(), false)
	t.errors("attempt to read beyond buffer limit", b.readByte, b)
end)

t.test("varints and strings roundtrip", function()
	local b = mumble.buffer()
	local values = { 0, 127, 128, 16383, 16384, 2097152, 268435456, 4294967296, -1, -4, -5, -100000 }
	for _, v in ipairs(values) do b:writeVarInt(v) end
	t.eq(b:writeString("hello\0world"), 11)
	for _, v in ipairs(values) do t.eq(b:readVarInt(), v) end
	t.eq(b:readString(), "hello\0world")
	t.errors("attempt to read beyond buffer limit", b.readVarInt, b)
end)

t.test("raw reads and writes", function()
	local b = mumble.buffer()
	t.eq(b:write("abcdef"), 6)
	local other = mumble.buffer()
	other:write("xyz")
	t.eq(b:write(other), 3)
	t.eq(b:read(2), "ab")
	local x, y = b:read(1, 1)
	t.eq(x, "c")
	t.eq(y, "d")
	t.eq(b:read("*a"), "efxyz")
	t.errors("invalid format", b.read, b, "*x")
	t.errors("attempt to read beyond buffer limit", b.read, b, 1)
	t.errors("string or mumble.buffer expected", b.write, b, 12)
end)

t.test("heads, seek, pack and reset", function()
	local b = mumble.buffer()
	b:write("abcdef")
	t.eq(b.read_head, 0)
	t.eq(b.write_head, 6)
	t.eq(b[0], "a")
	t.eq(b[5], "f")
	t.eq(b[6], nil)

	t.eq(b:seek("read", "set", 2), 2)
	t.eq(b:seek("read", "cur", 1), 3)
	local r, w = b:seek("both", "set", 1)
	t.eq(r, 1)
	t.eq(w, 1)
	t.eq(b:seek("write", "set", 6), 6)
	t.eq(b.length, 5)

	b:read(2)
	b:pack()
	t.eq(b.read_head, 0)
	t.eq(b.write_head, 3)
	t.eq(b:read("*a"), "def")

	b:flip()
	t.eq(b.read_head, 0)
	b:reset()
	t.eq(b.write_head, 0)
	t.eq(b:isEmpty(), true)
end)

t.run()
